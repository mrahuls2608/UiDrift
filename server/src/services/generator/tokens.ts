import type { ColorGroup, ComponentGroup, ReportTokens, ValueCount } from '@uidrift/shared';
import { parsePx } from '../analysis/normalize.js';

export const FONT_SIZE_NAMES = ['xs', 'sm', 'base', 'lg', 'xl', '2xl', '3xl', '4xl'];
export const RADIUS_NAMES = ['sm', 'md', 'lg', 'xl'];

export interface TokenInput {
  colors: ColorGroup[];
  fontSizes: ValueCount[];
  fontFamilies: ValueCount[];
  spacing: ValueCount[];
  radius: ValueCount[];
  groups: ComponentGroup[];
}

export interface TokenSet {
  color: Record<string, string>;
  fontFamily: Record<string, string>;
  fontSize: Record<string, string>;
  space: Record<string, string>;
  radius: Record<string, string>;
}

const byPx = (a: ValueCount, b: ValueCount) => parsePx(a.value) - parsePx(b.value);
const SAFE_VALUE = /^[#a-z0-9 .,%()-]+$/i;

/** Values come from scanned sites, so only plain CSS values make it into generated files. */
function safe(value: string): string | undefined {
  return SAFE_VALUE.test(value) ? value : undefined;
}

function primaryColor(groups: ComponentGroup[], fallback?: string): string | undefined {
  const button = groups.find((g) => g.type === 'button' && g.styles.bg?.startsWith('#'));
  return button?.styles.bg ?? fallback;
}

export function buildTokenSet(input: TokenInput): TokenSet {
  const color: Record<string, string> = {};
  input.colors.slice(0, 12).forEach((c, i) => {
    const v = safe(c.hex);
    if (v) color[String(i + 1)] = v;
  });
  const primary = primaryColor(input.groups, input.colors[0]?.hex);
  if (primary && safe(primary)) color.primary = primary;

  const fontFamily: Record<string, string> = {};
  const family = input.fontFamilies.find((f) => f.value !== 'inherit')?.value;
  const safeFamily = family?.replace(/[^a-z0-9 -]/gi, '').trim();
  if (safeFamily) fontFamily.base = `'${safeFamily}', system-ui, sans-serif`;

  const fontSize: Record<string, string> = {};
  [...input.fontSizes.slice(0, 8)].sort(byPx).forEach((f, i) => {
    const v = safe(f.value);
    if (v) fontSize[FONT_SIZE_NAMES[i] as string] = v;
  });

  const space: Record<string, string> = {};
  [...input.spacing.slice(0, 8)].sort(byPx).forEach((s, i) => {
    const v = safe(s.value);
    if (v) space[String(i + 1)] = v;
  });

  const radius: Record<string, string> = {};
  [...input.radius.slice(0, 4)].sort(byPx).forEach((r, i) => {
    const v = safe(r.value);
    if (v) radius[RADIUS_NAMES[i] as string] = v;
  });

  return { color, fontFamily, fontSize, space, radius };
}

const PREFIX: Record<keyof TokenSet, string> = {
  color: 'color',
  fontFamily: 'font-family',
  fontSize: 'font-size',
  space: 'space',
  radius: 'radius',
};

export function tokensToCss(set: TokenSet): string {
  const lines = [
    '/* Generated by UIDrift from the most used values on the scanned site. */',
    ':root {',
  ];
  for (const key of Object.keys(PREFIX) as Array<keyof TokenSet>) {
    for (const [name, value] of Object.entries(set[key]))
      lines.push(`  --${PREFIX[key]}-${name}: ${value};`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

export function buildTokens(input: TokenInput): ReportTokens & { set: TokenSet } {
  const set = buildTokenSet(input);
  return { css: tokensToCss(set), json: { ...set }, set };
}

/** Reverse lookup used by code generation: raw value → `var(--token)` when one matches. */
export function tokenLookup(set: TokenSet): (value: string | undefined) => string | undefined {
  const map = new Map<string, string>();
  for (const key of Object.keys(PREFIX) as Array<keyof TokenSet>) {
    for (const [name, value] of Object.entries(set[key])) {
      if (key === 'color' && name === 'primary') continue;
      if (!map.has(`${key}:${value}`)) map.set(`${key}:${value}`, `var(--${PREFIX[key]}-${name})`);
    }
  }
  if (set.color.primary) map.set(`color:${set.color.primary}`, 'var(--color-primary)');
  return (value) => {
    if (!value) return undefined;
    for (const key of ['color', 'fontSize', 'space', 'radius'] as const) {
      const hit = map.get(`${key}:${value}`);
      if (hit) return hit;
    }
    return undefined;
  };
}
