'use client';

import { useState } from 'react';
import { Download } from 'lucide-react';
import type { ReportDTO } from '@uidrift/shared';
import { Button } from '@/components/ui/Button';
import { CodeBlock } from '@/components/ui/CodeBlock';
import { Tabs } from '@/components/ui/Tabs';
import { useToast } from '@/components/ui/Toast';
import { Section } from '../Section';

export default function ExportSection({ report }: { report: ReportDTO }) {
  const [tab, setTab] = useState('css');
  const [zipping, setZipping] = useState(false);
  const toast = useToast();
  const json = JSON.stringify(report.tokens.json, null, 2);
  const componentFiles = report.components.filter((f) => f.path.startsWith('components/'));

  const downloadZip = async () => {
    setZipping(true);
    try {
      const { default: JSZip } = await import('jszip');
      const zip = new JSZip();
      const root = zip.folder(`uidrift-${report.domain}`) ?? zip;
      root.file('tokens.json', json);
      for (const f of report.components) root.file(f.path, f.content);
      root.file(
        'README.md',
        `# Design system starter for ${report.domain}\n\nGenerated by UIDrift. Import \`tokens.css\` once, then use the components from \`components/\`.\n`,
      );
      const blob = await zip.generateAsync({ type: 'blob' });
      const url = URL.createObjectURL(blob);
      const a = Object.assign(document.createElement('a'), {
        href: url,
        download: `uidrift-${report.domain}.zip`,
      });
      a.click();
      URL.revokeObjectURL(url);
      toast('success', 'ZIP downloaded.');
    } catch {
      toast('error', 'Could not create the ZIP file.');
    } finally {
      setZipping(false);
    }
  };

  return (
    <Section
      id="export"
      title="Export"
      description="Design tokens and starter React components generated from the most used values and variants."
    >
      <div>
        <Button onClick={downloadZip} loading={zipping}>
          <Download aria-hidden size={16} /> Download ZIP
        </Button>
      </div>
      <Tabs
        label="Export formats"
        value={tab}
        onChange={setTab}
        items={[
          { id: 'css', label: 'tokens.css' },
          { id: 'json', label: 'tokens.json' },
          { id: 'react', label: 'React components' },
        ]}
      >
        {tab === 'css' && (
          <CodeBlock code={report.tokens.css} language="css" filename="tokens.css" />
        )}
        {tab === 'json' && <CodeBlock code={json} language="json" filename="tokens.json" />}
        {tab === 'react' && (
          <div className="flex flex-col gap-4">
            {componentFiles.map((f) => (
              <CodeBlock key={f.path} code={f.content} language="tsx" filename={f.path} />
            ))}
          </div>
        )}
      </Tabs>
    </Section>
  );
}
